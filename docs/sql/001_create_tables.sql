-- MySQL 8.4 / InnoDB / utf8mb4. 在 DataGrip 选择 seal_card 数据库后执行。
-- 六张表；纯建表，不含 DROP、测试账号、种子客户或真实影像。
-- 不使用 IF NOT EXISTS，以免静默掩盖已有表结构不一致。
SET NAMES utf8mb4;

CREATE TABLE seal_card (
  id BIGINT NOT NULL AUTO_INCREMENT COMMENT '内部主键',
  card_no VARCHAR(32) NOT NULL COMMENT '业务卡号',
  customer_no VARCHAR(32) NOT NULL COMMENT '外部客户中心CIF',
  branch_no VARCHAR(32) NOT NULL COMMENT '管理机构',
  current_version_id BIGINT NULL COMMENT '当前生效版本，须属于本卡',
  status VARCHAR(16) NOT NULL DEFAULT 'ENABLED',
  row_version INT NOT NULL DEFAULT 0 COMMENT '乐观锁版本',
  created_by VARCHAR(32) NOT NULL,
  disabled_by VARCHAR(32) NULL,
  disabled_at DATETIME(3) NULL,
  disable_reason VARCHAR(500) NULL,
  remark VARCHAR(500) NULL,
  created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
  PRIMARY KEY (id),
  UNIQUE KEY uk_card_no (card_no),
  KEY idx_card_customer_status (customer_no, status),
  KEY idx_card_branch (branch_no, status, id),
  KEY idx_card_current (id, current_version_id),
  CONSTRAINT ck_card_status CHECK (status IN ('ENABLED','DISABLED')),
  CONSTRAINT ck_card_lock CHECK (row_version >= 0),
  CONSTRAINT ck_card_disabled_pointer CHECK (status <> 'DISABLED' OR current_version_id IS NULL)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_as_cs COMMENT='印鉴卡主表';

CREATE TABLE seal_card_version (
  id BIGINT NOT NULL AUTO_INCREMENT,
  seal_card_id BIGINT NOT NULL,
  version_no INT NOT NULL,
  status VARCHAR(24) NOT NULL DEFAULT 'UPLOADING',
  effective_from DATETIME(3) NULL,
  effective_to DATETIME(3) NULL,
  created_by VARCHAR(32) NOT NULL,
  approved_by VARCHAR(32) NULL,
  approved_at DATETIME(3) NULL,
  submitted_at DATETIME(3) NULL,
  rejected_by VARCHAR(32) NULL,
  rejected_at DATETIME(3) NULL,
  reject_reason VARCHAR(500) NULL,
  expected_image_count INT NOT NULL COMMENT '申请上传页数，完成时须核对实际READY页数',
  authorization_ref VARCHAR(128) NULL COMMENT '共用/变更授权依据索引，不存原文',
  change_reason VARCHAR(500) NULL,
  created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
  active_card_id BIGINT GENERATED ALWAYS AS (CASE WHEN status='ACTIVE' THEN seal_card_id ELSE NULL END) STORED,
  PRIMARY KEY (id),
  UNIQUE KEY uk_version_number (seal_card_id, version_no),
  UNIQUE KEY uk_version_card_id (seal_card_id, id),
  UNIQUE KEY uk_version_one_active (active_card_id),
  KEY idx_version_approval (status, created_at, id),
  KEY idx_version_effective (seal_card_id, effective_from, effective_to),
  CONSTRAINT fk_version_card FOREIGN KEY (seal_card_id) REFERENCES seal_card(id),
  CONSTRAINT ck_version_number CHECK (version_no > 0 AND expected_image_count > 0),
  CONSTRAINT ck_version_status CHECK (status IN ('UPLOADING','PENDING_APPROVAL','APPROVED','ACTIVE','ARCHIVED','FAILED','REJECTED')),
  CONSTRAINT ck_version_interval CHECK (effective_to IS NULL OR (effective_from IS NOT NULL AND effective_to > effective_from)),
  CONSTRAINT ck_version_review CHECK (approved_by IS NULL OR approved_by <> created_by),
  CONSTRAINT ck_version_rejector CHECK (rejected_by IS NULL OR rejected_by <> created_by),
  CONSTRAINT ck_version_approved CHECK (status NOT IN ('APPROVED','ACTIVE','ARCHIVED') OR (approved_by IS NOT NULL AND approved_at IS NOT NULL AND effective_from IS NOT NULL)),
  CONSTRAINT ck_version_archived CHECK (status <> 'ARCHIVED' OR effective_to IS NOT NULL),
  CONSTRAINT ck_version_rejected CHECK (status <> 'REJECTED' OR (rejected_by IS NOT NULL AND rejected_at IS NOT NULL AND reject_reason IS NOT NULL))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_as_cs COMMENT='印鉴卡版本与复核记录';

-- 复合外键保证当前指针不能指向其他卡的版本；ACTIVE语义仍由同一业务事务保证。
ALTER TABLE seal_card ADD CONSTRAINT fk_card_current_version
  FOREIGN KEY (id, current_version_id) REFERENCES seal_card_version(seal_card_id, id);

CREATE TABLE seal_card_account (
  id BIGINT NOT NULL AUTO_INCREMENT,
  seal_card_id BIGINT NOT NULL,
  version_id BIGINT NOT NULL COMMENT '账户范围所属审批版本快照',
  account_no VARCHAR(32) NOT NULL COMMENT '单位结算账号，外部引用',
  binding_status VARCHAR(16) NOT NULL DEFAULT 'PENDING',
  effective_from DATETIME(3) NULL COMMENT '待审核时为空，生效时必填',
  effective_to DATETIME(3) NULL,
  approved_by VARCHAR(32) NULL,
  approved_at DATETIME(3) NULL,
  authorization_ref VARCHAR(128) NULL,
  created_by VARCHAR(32) NOT NULL,
  created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  PRIMARY KEY (id),
  UNIQUE KEY uk_binding_version_account (version_id, account_no),
  UNIQUE KEY uk_binding_history (seal_card_id, account_no, effective_from),
  KEY idx_binding_lookup (account_no, binding_status, effective_from, effective_to),
  KEY idx_binding_card_version (seal_card_id, version_id),
  CONSTRAINT fk_binding_version FOREIGN KEY (seal_card_id, version_id) REFERENCES seal_card_version(seal_card_id, id),
  CONSTRAINT ck_binding_status CHECK (binding_status IN ('PENDING','ACTIVE','ENDED','REJECTED')),
  CONSTRAINT ck_binding_interval CHECK (effective_to IS NULL OR (effective_from IS NOT NULL AND effective_to > effective_from)),
  CONSTRAINT ck_binding_review CHECK (approved_by IS NULL OR approved_by <> created_by),
  CONSTRAINT ck_binding_active CHECK (binding_status NOT IN ('ACTIVE','ENDED') OR (effective_from IS NOT NULL AND approved_by IS NOT NULL AND approved_at IS NOT NULL)),
  CONSTRAINT ck_binding_ended CHECK (binding_status <> 'ENDED' OR effective_to IS NOT NULL)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_as_cs COMMENT='按审批版本保存的账户适用范围';

CREATE TABLE seal_card_image (
  id BIGINT NOT NULL AUTO_INCREMENT,
  version_id BIGINT NOT NULL,
  page_no INT NOT NULL,
  image_id VARCHAR(128) NOT NULL COMMENT '私有平台对象ID，非公网URL',
  sha256 CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  mime_type VARCHAR(40) NOT NULL,
  file_size BIGINT NOT NULL,
  storage_status VARCHAR(16) NOT NULL DEFAULT 'READY',
  created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  PRIMARY KEY (id),
  UNIQUE KEY uk_image_page (version_id, page_no),
  KEY idx_image_object (image_id),
  CONSTRAINT fk_image_version FOREIGN KEY (version_id) REFERENCES seal_card_version(id),
  CONSTRAINT ck_image_size CHECK (page_no > 0 AND file_size > 0),
  CONSTRAINT ck_image_hash CHECK (REGEXP_LIKE(sha256, '^[0-9a-f]{64}$', 'c')),
  CONSTRAINT ck_image_status CHECK (storage_status IN ('READY','FAILED'))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_as_cs COMMENT='影像索引，不存图片正文';

CREATE TABLE seal_card_audit_log (
  id BIGINT NOT NULL AUTO_INCREMENT,
  seal_card_id BIGINT NULL COMMENT '失败或无候选查询允许为空',
  version_id BIGINT NULL,
  target_ref VARCHAR(128) NULL COMMENT '未找到的目标等非敏感引用',
  action VARCHAR(32) NOT NULL COMMENT 'UPLOAD/SUBMIT/QUERY/APPROVE/REJECT/ACTIVATE/DISABLE/BIND/UNBIND/VIEW_IMAGE',
  operator_id VARCHAR(32) NOT NULL,
  branch_no VARCHAR(32) NOT NULL,
  request_id VARCHAR(64) NOT NULL,
  result VARCHAR(16) NOT NULL,
  error_code VARCHAR(64) NULL COMMENT '失败码，不写原始敏感报错',
  purpose VARCHAR(128) NULL COMMENT '业务用途/流程引用',
  created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  PRIMARY KEY (id),
  KEY idx_audit_card_time (seal_card_id, created_at, id),
  KEY idx_audit_request (request_id),
  KEY idx_audit_operator_time (operator_id, created_at),
  KEY idx_audit_branch_time (branch_no, created_at),
  CONSTRAINT ck_audit_result CHECK (result IN ('SUCCESS','FAIL'))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_as_cs COMMENT='追加审计；无外键以允许失败/未找到目标留痕';

CREATE TABLE seal_upload_task (
  id BIGINT NOT NULL AUTO_INCREMENT,
  idempotency_key VARCHAR(64) NOT NULL,
  request_hash CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  version_id BIGINT NOT NULL,
  operator_id VARCHAR(32) NOT NULL,
  branch_no VARCHAR(32) NOT NULL,
  request_id VARCHAR(64) NOT NULL,
  payload JSON NOT NULL COMMENT '私有暂存对象及页摘要清单，不含图片字节/凭证',
  task_status VARCHAR(20) NOT NULL DEFAULT 'PENDING',
  retry_count INT NOT NULL DEFAULT 0,
  next_retry_at DATETIME(3) NULL,
  lock_owner VARCHAR(128) NULL,
  lock_until DATETIME(3) NULL,
  lock_token BIGINT NOT NULL DEFAULT 0 COMMENT '递增抢占令牌，防过期执行者写入',
  last_error_code VARCHAR(64) NULL,
  last_error_message VARCHAR(500) NULL COMMENT '脱敏摘要',
  completed_at DATETIME(3) NULL,
  created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
  PRIMARY KEY (id),
  UNIQUE KEY uk_upload_idempotency (idempotency_key),
  UNIQUE KEY uk_upload_version (version_id),
  KEY idx_upload_retry (task_status, next_retry_at, id),
  KEY idx_upload_lease (task_status, lock_until),
  CONSTRAINT fk_upload_version FOREIGN KEY (version_id) REFERENCES seal_card_version(id),
  CONSTRAINT ck_upload_status CHECK (task_status IN ('PENDING','PROCESSING','SUCCESS','RETRY','FAILED')),
  CONSTRAINT ck_upload_counters CHECK (retry_count >= 0 AND lock_token >= 0),
  CONSTRAINT ck_upload_hash CHECK (REGEXP_LIKE(request_hash, '^[0-9a-f]{64}$', 'c')),
  CONSTRAINT ck_upload_lease CHECK (task_status <> 'PROCESSING' OR (lock_owner IS NOT NULL AND lock_until IS NOT NULL)),
  CONSTRAINT ck_upload_success CHECK (task_status <> 'SUCCESS' OR completed_at IS NOT NULL)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_as_cs COMMENT='上传幂等与可恢复补偿任务';
